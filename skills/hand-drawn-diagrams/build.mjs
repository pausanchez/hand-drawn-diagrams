// Bundles src/render.mjs and its dependencies into scripts/render.mjs (+ scripts/resvg.wasm),
// so the skill runs with plain Node and no npm install.
// `node build.mjs --check` fails if the committed bundle is out of date (used in CI).
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const check = process.argv.includes('--check');
const outDir = check ? fs.mkdtempSync(path.join(HERE, '.build-check-')) : path.join(HERE, 'scripts');

await build({
  entryPoints: [path.join(HERE, 'src/render.mjs')],
  outfile: path.join(outDir, 'render.mjs'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node18',
  minify: true,
  legalComments: 'eof',
  banner: { js: "// GENERATED by `npm run build` from src/render.mjs. Do not edit by hand.\nimport { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" },
  logLevel: 'warning',
});
fs.copyFileSync(path.join(HERE, 'node_modules/@resvg/resvg-wasm/index_bg.wasm'), path.join(outDir, 'resvg.wasm'));

// Licence notices for everything shipped inside the bundle and the wasm file.
const BUNDLED = ['roughjs', 'points-on-curve', 'points-on-path', 'path-data-parser', 'hachure-fill', 'elkjs', 'opentype.js', '@resvg/resvg-wasm'];
let notices = '# Third-party notices\n\n`scripts/render.mjs` and `scripts/resvg.wasm` are built from the packages below, unmodified.\n' +
  'Each one keeps its own licence. The source of every package is available at the URL listed.\n';
for (const name of BUNDLED) {
  const dir = path.join(HERE, 'node_modules', name);
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const repo = String(pkg.repository?.url ?? pkg.repository ?? pkg.homepage ?? '').replace(/^git\+/, '').replace(/\.git$/, '');
  const lic = fs.readdirSync(dir).find((f) => /^licen[cs]e/i.test(f));
  notices += `\n## ${name} ${pkg.version}\n\nLicence: ${pkg.license}${repo ? `  \nSource: ${repo}` : ''}\n`;
  notices += lic ? `\n\`\`\`\n${fs.readFileSync(path.join(dir, lic), 'utf8').trim()}\n\`\`\`\n` : `\nFull licence text: https://spdx.org/licenses/${pkg.license}.html\n`;
}
fs.writeFileSync(path.join(outDir, 'THIRD_PARTY_NOTICES.md'), notices);

if (check) {
  let stale = [];
  for (const f of ['render.mjs', 'resvg.wasm', 'THIRD_PARTY_NOTICES.md']) {
    const a = path.join(outDir, f), b = path.join(HERE, 'scripts', f);
    if (!fs.existsSync(b) || !fs.readFileSync(a).equals(fs.readFileSync(b))) stale.push('scripts/' + f);
  }
  fs.rmSync(outDir, { recursive: true, force: true });
  if (stale.length) { console.error(`Bundle out of date: ${stale.join(', ')}. Run \`npm run build\` and commit.`); process.exit(1); }
  console.log('Bundle up to date.');
} else {
  for (const f of ['render.mjs', 'resvg.wasm', 'THIRD_PARTY_NOTICES.md']) console.log(`scripts/${f}  ${(fs.statSync(path.join(outDir, f)).size / 1024).toFixed(0)} KB`);
}
